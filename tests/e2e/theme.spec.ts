import { expect, test } from '@playwright/test'

test('theme switches without resetting the scene and persists through SSR and login', async ({
  page,
}) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('.planet-target')).toHaveCount(8)
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  const canvas = await page.locator('.universe-canvas > canvas').elementHandle()
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await expect(page.getByRole('radio', { name: 'Dark', exact: true })).toBeChecked()
  // Native radio keyboard navigation also makes the control usable without a mouse.
  await page.getByRole('radio', { name: 'Dark', exact: true }).focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('radio', { name: 'Light', exact: true })).toBeChecked()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await expect(page.locator('html')).toHaveCSS('opacity', '1')
  await expect(page.locator('.event-horizon')).toHaveCSS('opacity', '0.5')
  await expect(page.getByRole('dialog')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await page.screenshot({ path: 'artifacts/theme-light-settings.png' })
  await page.getByRole('button', { name: 'Close settings' }).click()
  expect(await canvas!.evaluate((el) => el.isConnected)).toBe(true)
  await expect(page.locator('.planet-target')).toHaveCount(8)
  await page.screenshot({ path: 'artifacts/theme-light-universe.png' })
  await page.getByRole('button', { name: 'List', exact: true }).click()
  await page.locator('.project-card').first().click()
  await expect(page.locator('.project-panel')).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await page.screenshot({ path: 'artifacts/theme-light-details.png' })
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  const html = await (await page.request.get('/login')).text()
  expect(html).toMatch(/<html[^>]*data-theme="light"/)
  await page.goto('/login')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await expect(page.locator('.auth-page')).toHaveCSS('background-color', 'rgb(244, 247, 245)')
  await page.screenshot({ path: 'artifacts/theme-light-login.png' })
  await page.goto('/')
  await expect(page.locator('.planet-target')).toHaveCount(8)
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByText('Dark', { exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: 'Close settings' }).click()
  await page.reload()
  await expect(page.locator('html')).toHaveCSS('background-color', 'rgb(11, 15, 18)')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.screenshot({ path: 'artifacts/cinematic-dark-universe.png' })
  expect(errors).toEqual([])
})

test('light theme controls and content fit a narrow mobile viewport', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 568 })
  await page.goto('/')
  await expect(page.locator('.planet-target')).toHaveCount(8)
  await page.getByRole('button', { name: 'Settings', exact: true }).click()
  await page.getByText('Light', { exact: true }).click()
  await expect(page.getByRole('radio', { name: 'Light', exact: true })).toBeChecked()
  const option = page.locator('.theme-option').last()
  expect((await option.boundingBox())!.height).toBeGreaterThanOrEqual(44)
  expect(
    await page.getByRole('dialog').evaluate((el) => el.scrollWidth <= el.clientWidth + 1),
  ).toBe(true)
  await page.screenshot({ path: 'artifacts/theme-light-mobile-settings.png' })
  const back = page.getByRole('button', { name: 'Back to your universe' })
  await back.scrollIntoViewIfNeeded()
  await back.click()
  await expect(page.locator('.planet-target')).toHaveCount(8)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: 'artifacts/theme-light-mobile.png', fullPage: true })
  await page.goto('/login')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
